// Объявление публичного класса
public class Main {
// Главный метод программы — точка входа
    public static void main(String[] args) {
        int n = 10; // Количество чисел гармонического ряда
        System.out.println("Первые 10 чисел гармонического ряда:");

        // Вычисляем и выводим гармонический ряд
// Цикл для прохода по элементам массива
        for (int i = 1; i <= n; i++) {
            double harmonicNumber = 1.0 / i; // Число гармонического ряда
            System.out.printf("H(%d) = %.4f\n", i, harmonicNumber); // Форматируем вывод с 4 знаками после запятой
        }
    }
}
