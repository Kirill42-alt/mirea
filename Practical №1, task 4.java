import java.util.Scanner;

// Объявление публичного класса
public class ArraySumMinMax {
// Главный метод программы — точка входа
    public static void main(String[] args) {
        // Создание объекта Scanner для считывания ввода пользователя
        Scanner scanner = new Scanner(System.in);
        
        // Ввод размера массива
        System.out.print("Введите размер массива: ");
        int size = scanner.nextInt(); // Считываем размер массива
        
        // Создаём массив указанного размера
        int[] numbers = new int[size];
        
        // Ввод элементов массива пользователем
        System.out.println("Введите элементы массива:");
        int i = 0;
        do {
            numbers[i] = scanner.nextInt(); // Считываем элемент массива
            i++; // Увеличиваем индекс
        } while (i < size); // Повторяем, пока не введены все элементы
        
        // Инициализация переменных для расчёта суммы, максимального и минимального значений
// Переменная для хранения суммы
        int sum = 0; // Переменная для хранения суммы элементов
        int max = numbers[0]; // Инициализируем максимум первым элементом массива
        int min = numbers[0]; // Инициализируем минимум первым элементом массива
        i = 0; // Сбрасываем индекс для следующего цикла
        
        // Цикл while для вычисления суммы, максимального и минимального значений
        while (i < size) {
// Прибавление текущего элемента массива к сумме
            sum += numbers[i]; // Добавляем элемент к сумме
            
            // Проверяем, является ли текущий элемент максимальным
            if (numbers[i] > max) {
                max = numbers[i]; // Обновляем максимум
            }
            
            // Проверяем, является ли текущий элемент минимальным
            if (numbers[i] < min) {
                min = numbers[i]; // Обновляем минимум
            }
            
            i++; // Увеличиваем индекс
        }
        
        // Вывод результатов на экран
// Вывод суммы на экран
        System.out.println("Сумма элементов массива: " + sum); // Вывод суммы
        System.out.println("Максимальный элемент: " + max); // Вывод максимального значения
        System.out.println("Минимальный элемент: " + min); // Вывод минимального значения
    }
}
