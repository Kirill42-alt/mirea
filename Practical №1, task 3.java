// Объявление публичного класса
public class ArraySumAverage {
// Главный метод программы — точка входа
    public static void main(String[] args) {
        // Инициализация массива
// Объявление и инициализация массива целых чисел
        int[] numbers = {10, 20, 30, 40, 50};
        
// Переменная для хранения суммы
        int sum = 0;
        
        // Вычисление суммы элементов массива
// Цикл для прохода по элементам массива
        for (int i = 0; i < numbers.length; i++) {
// Прибавление текущего элемента массива к сумме
            sum += numbers[i];
        }
        
        // Вычисление среднего арифметического
// Вычисление среднего значения (каст к double для дробного результата)
        double average = (double) sum / numbers.length;
        
        // Вывод результатов на экран
// Вывод суммы на экран
        System.out.println("Сумма элементов массива: " + sum);
// Вывод среднего на экран
        System.out.println("Среднее арифметическое: " + average);
    }
}
